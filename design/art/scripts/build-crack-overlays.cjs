#!/usr/bin/env node
// Trims Crack A (design/art/game/crack-overlay.png) to each vessel's silhouette, so the one approved
// overlay can sit on any vessel without spilling past its edges. Same result on web, iOS and Android.
// Run from the repo root: NODE_PATH=<folder with sharp>/node_modules node design/art/scripts/build-crack-overlays.cjs
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const SIZE = 512;
const GLASS_BOOST = 3; // Clear glass is mostly transparent; cracks still need to show on it.
const manifest = fs.readFileSync('mobile/src/art/manifest.ts', 'utf8');
const vessels = [...manifest.matchAll(/['"]?([\w-]+)['"]?: \{\s*assembled: require\('[^']*\/(vessel-[\w-]+)\.webp'\)/g)].map((m) => ({ kind: m[1], file: m[2] }));

(async () => {
  const crack = await sharp('design/art/game/crack-overlay.png').resize(SIZE, SIZE).ensureAlpha().raw().toBuffer();
  fs.mkdirSync('public/art/game/cracks', { recursive: true });
  for (const { file } of vessels) {
    const alpha = await sharp(`public/art/vessels/${file}.webp`).resize(SIZE, SIZE).ensureAlpha().extractChannel('alpha').raw().toBuffer();
    const out = Buffer.from(crack);
    for (let i = 0; i < alpha.length; i++) out[i * 4 + 3] = Math.round(crack[i * 4 + 3] * Math.min(1, (alpha[i] / 255) * GLASS_BOOST));
    await sharp(out, { raw: { width: SIZE, height: SIZE, channels: 4 } }).webp({ quality: 82, alphaQuality: 90 }).toFile(path.join('public/art/game/cracks', `${file.replace('vessel-', '')}.webp`));
  }
  const rows = vessels.map(({ kind, file }) => `  ${JSON.stringify(kind)}: require('../../../public/art/game/cracks/${file.replace('vessel-', '')}.webp'),`);
  fs.writeFileSync('mobile/src/art/crackOverlays.ts', `// Generated by design/art/scripts/build-crack-overlays.cjs. Do not edit by hand.\nimport type { ImageSourcePropType } from 'react-native';\n\nexport const crackOverlays: Record<string, ImageSourcePropType> = {\n${rows.join('\n')}\n};\n`);
  console.log(`${vessels.length} crack overlays`);
})();
