export function useF1Text() {
  const { language } = useLanguage();
  return (key: keyof typeof strings.zh, ...args: any[]): string => {
    const value = strings[language][key];
    return typeof value === "function" ? (value as (...args: any[]) => string)(...args) : value;
  };
}
