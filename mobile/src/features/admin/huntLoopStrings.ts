export type HuntLoopText = typeof strings.zh;
export const huntLoopStrings = strings;
export function useHuntLoopText(): HuntLoopText {
  const { language } = useLanguage();
  return strings[language] as HuntLoopText;
}
/** The message for a refused write. */
export const loopError = (h: HuntLoopText, e: unknown) => h.error[(e as Error)?.message] ?? h.error.failed;
